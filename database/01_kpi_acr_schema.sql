-- Enterprise HRM KPI / Annual Performance Appraisal (ACR)
-- Step 1 of 2: database foundation only. Run this script before the function script.
-- Schema: hrm_kpi
--
-- Visible menus supported by this schema:
--   1. Competency Master
--   2. Appraiser Mapping
--   3. KPI Reference
--   4. ACR Submission
--   5. Annual Performance Appraisal Form
--
-- Employee and supervisor values are kept as employee_no because existing Enterprise HRM HRM
-- functions exchange employee identifiers this way. Do not add a foreign key until
-- the authoritative employee master table/key is confirmed in the live database.

CREATE TABLE IF NOT EXISTS hrm_kpi.kpi_competency (
    competency_no       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competency_name     text NOT NULL,
    description         text,
    active_stat         numeric(1, 0) NOT NULL DEFAULT 1,
    entryby             numeric,
    entryip             text,
    entrydate           timestamp without time zone NOT NULL DEFAULT now(),
    updateby            numeric,
    updateip            text,
    updatedate          timestamp without time zone,
    CONSTRAINT uq_kpi_competency_name UNIQUE (competency_name),
    CONSTRAINT ck_kpi_competency_active_stat CHECK (active_stat IN (0, 1))
);

CREATE TABLE IF NOT EXISTS hrm_kpi.kpi_reference (
    reference_no            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code          text NOT NULL,
    evaluation_from         date NOT NULL,
    evaluation_to           date NOT NULL,
    employee_due_date       date NOT NULL,
    supervisor_due_date     date,
    description             text,
    active_stat             numeric(1, 0) NOT NULL DEFAULT 1,
    cycle_status            text NOT NULL DEFAULT 'DRAFT',
    entryby                 numeric,
    entryip                 text,
    entrydate               timestamp without time zone NOT NULL DEFAULT now(),
    updateby                numeric,
    updateip                text,
    updatedate              timestamp without time zone,
    CONSTRAINT uq_kpi_reference_code UNIQUE (reference_code),
    CONSTRAINT ck_kpi_reference_dates CHECK (evaluation_to >= evaluation_from),
    CONSTRAINT ck_kpi_reference_cycle_status CHECK (cycle_status IN ('DRAFT', 'OPEN', 'CLOSED')),
    CONSTRAINT ck_kpi_reference_active_stat CHECK (active_stat IN (0, 1))
);

CREATE TABLE IF NOT EXISTS hrm_kpi.kpi_appraiser_mapping (
    mapping_no             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no           bigint NOT NULL REFERENCES hrm_kpi.kpi_reference(reference_no),
    employee_no            bigint NOT NULL,
    appraiser_employee_no  bigint NOT NULL,
    active_stat            numeric(1, 0) NOT NULL DEFAULT 1,
    entryby                numeric,
    entryip                text,
    entrydate              timestamp without time zone NOT NULL DEFAULT now(),
    updateby               numeric,
    updateip               text,
    updatedate             timestamp without time zone,
    CONSTRAINT ck_kpi_appraiser_mapping_active_stat CHECK (active_stat IN (0, 1)),
    CONSTRAINT ck_kpi_appraiser_mapping_not_self CHECK (employee_no <> appraiser_employee_no)
);

-- Only one currently-active appraiser is permitted for an employee in a reference/cycle.
CREATE UNIQUE INDEX IF NOT EXISTS ux_kpi_appraiser_mapping_active
    ON hrm_kpi.kpi_appraiser_mapping (reference_no, employee_no)
    WHERE active_stat = 1;

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_master (
    acr_no                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no               bigint NOT NULL REFERENCES hrm_kpi.kpi_reference(reference_no),
    employee_no                bigint NOT NULL,
    appraiser_employee_no      bigint NOT NULL,
    submission_status          text NOT NULL DEFAULT 'DRAFT',
    employee_submitted_at      timestamp without time zone,
    supervisor_submitted_at    timestamp without time zone,
    supervisor_performance     text,
    supervisor_explanation     text,
    whole_performance          text,
    final_decision             text,
    final_remarks              text,
    finalized_by               numeric,
    finalized_at               timestamp without time zone,
    entryby                    numeric,
    entryip                    text,
    entrydate                  timestamp without time zone NOT NULL DEFAULT now(),
    updateby                   numeric,
    updateip                   text,
    updatedate                 timestamp without time zone,
    CONSTRAINT uq_acr_master_reference_employee UNIQUE (reference_no, employee_no),
    CONSTRAINT ck_acr_master_status CHECK (submission_status IN ('DRAFT', 'EMPLOYEE_SUBMITTED', 'SUPERVISOR_SUBMITTED', 'MANAGEMENT_REVIEWED', 'FINALIZED', 'RETURNED')),
    CONSTRAINT ck_acr_master_supervisor_performance CHECK (supervisor_performance IS NULL OR supervisor_performance IN ('HIGHLY_SATISFACTORY', 'SATISFACTORY', 'UNSATISFACTORY')),
    CONSTRAINT ck_acr_master_whole_performance CHECK (whole_performance IS NULL OR whole_performance IN ('OUTSTANDING', 'VERY_GOOD', 'GOOD', 'ACCEPTABLE', 'POOR')),
    CONSTRAINT ck_acr_master_final_decision CHECK (final_decision IS NULL OR final_decision IN ('NORMAL_INCREMENT', 'SPECIAL_INCREMENT', 'PROMOTION', 'NO_INCREMENT'))
);

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_activity (
    activity_no                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acr_no                         bigint NOT NULL REFERENCES hrm_kpi.acr_master(acr_no) ON DELETE CASCADE,
    activity_description           text NOT NULL,
    employee_achievement_percent   numeric(5, 2),
    supervisor_achievement_percent numeric(5, 2),
    supervisor_comment             text,
    display_order                  integer NOT NULL DEFAULT 1,
    CONSTRAINT ck_acr_activity_employee_percent CHECK (employee_achievement_percent IS NULL OR employee_achievement_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_acr_activity_supervisor_percent CHECK (supervisor_achievement_percent IS NULL OR supervisor_achievement_percent BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_competency_rating (
    rating_no             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acr_no                bigint NOT NULL REFERENCES hrm_kpi.acr_master(acr_no) ON DELETE CASCADE,
    competency_no         bigint NOT NULL REFERENCES hrm_kpi.kpi_competency(competency_no),
    employee_rating       text,
    supervisor_rating     text,
    supervisor_comment    text,
    CONSTRAINT uq_acr_competency_rating UNIQUE (acr_no, competency_no),
    CONSTRAINT ck_acr_competency_employee_rating CHECK (employee_rating IS NULL OR employee_rating IN ('EXCELLENT', 'HIGH', 'AVERAGE', 'MARGINAL', 'LOW')),
    CONSTRAINT ck_acr_competency_supervisor_rating CHECK (supervisor_rating IS NULL OR supervisor_rating IN ('EXCELLENT', 'HIGH', 'AVERAGE', 'MARGINAL', 'LOW'))
);

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_development_need (
    development_no          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acr_no                  bigint NOT NULL REFERENCES hrm_kpi.acr_master(acr_no) ON DELETE CASCADE,
    area_to_improve         text NOT NULL,
    action_required         text,
    responsible_person      text,
    target_deadline         date,
    supervisor_comment      text,
    display_order           integer NOT NULL DEFAULT 1,
    CONSTRAINT ck_acr_development_need_order CHECK (display_order BETWEEN 1 AND 3)
);

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_next_year_target (
    target_no               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acr_no                  bigint NOT NULL REFERENCES hrm_kpi.acr_master(acr_no) ON DELETE CASCADE,
    target_description      text NOT NULL,
    supervisor_comment      text,
    display_order           integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS hrm_kpi.acr_approval_history (
    approval_no             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acr_no                  bigint NOT NULL REFERENCES hrm_kpi.acr_master(acr_no) ON DELETE CASCADE,
    action_by               numeric NOT NULL,
    action_role             text NOT NULL,
    action_type             text NOT NULL,
    remarks                 text,
    action_date             timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_acr_approval_action_type CHECK (action_type IN ('SUBMIT', 'RETURN', 'REVIEW', 'FINALIZE'))
);

CREATE INDEX IF NOT EXISTS ix_acr_master_reference_status
    ON hrm_kpi.acr_master (reference_no, submission_status);

CREATE INDEX IF NOT EXISTS ix_acr_master_appraiser_status
    ON hrm_kpi.acr_master (appraiser_employee_no, submission_status);

